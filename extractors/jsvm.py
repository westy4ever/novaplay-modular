def S(x):
    """formatting like the browser trace (__S)"""
    try:
        if isinstance(x, str):
            return "s%d:%s" % (len(x), x[:120])
        if x is None:
            return "null"
        if x is UNDEF:
            return "undefined"
        if x is True:
            return "true"
        if x is False:
            return "false"
        if isinstance(x, JSBigInt):
            return "n:" + str(int(x))
        if isinstance(x, (int, float)):
            return num_to_str(x)
        if isinstance(x, JSFunction):
            n = x.name or "?"
            return "fn:" + n
        if isinstance(x, TypedArray):
            b = x.tobytes()
            nm = "u" if x.is_buffer else x.kind
            return "%s%d:%s" % (nm, len(b), b[:48].hex())
        if isinstance(x, list):
            return "A%d[%s]" % (len(x), ",".join(S(y) for y in x[:6]))
        if isinstance(x, JSPromise):
            return "promise"
        if isinstance(x, JSRegExp):
            return "O{}"
        if isinstance(x, JSObject):
            return "O{" + ",".join(list(x.keys())[:8]) + "}"
        return "?"
    except Exception:
        return "?"


class VM(object):
    def __init__(self, spec, env, glob, trace=None, max_ops=20000000):
        """env: name -> value for the VM's own name tables (by key name);
        glob: the generic global object (nw)."""
        self.spec = spec
        self.code = spec.code
        self.disp = spec.disp
        self.trace = trace
        self.ops = 0
        self.max_ops = max_ops
        self.strs = {}
        self.missing = set()
        self.unresolved = set()
        self.lits = {}
        _fmap = {"+": 1, "-": 2, "<": 3, ">": 4, "<=": 5, ">=": 6, "===": 7, "==": 7, "!==": 8, "!=": 8,
                 "&": 9, "|": 10, "^": 11, ">>": 12, ">>>": 13}
        self.fast = [_fmap.get(n, 0) for n in spec.binops] + [0] * (256 - len(spec.binops))
        # name tables resolved in lookup order: first table wins
        self.names = {}
        for table in spec.table_names:
            for name, expr in table:
                pass
        self.tables = []
        for table in spec.table_names:
            d = {}
            for name, expr in table:
                if name in env:
                    d[name] = env[name]
                else:
                    self.missing.add(name)
                    d[name] = UNDEF
            self.tables.append(d)
        self.glob = {}
        for n in _GLOBAL_NAMES:
            if n in glob:
                self.glob[n] = glob[n]

    # name lookup: scope chain, then the tables, then the globals object
    def _resolve(self, scope, name):
        s = scope.find(name)
        if s is not None:
            return s.vars[name], True
        for d in self.tables:
            if name in d:
                return d[name], False
        if name in self.glob:
            return self.glob[name], False
        return _NF, False

    def _str(self, pc):
        c = self.code
        n = (c[pc] << 8) | c[pc + 1]
        r = self.strs.get(pc)
        if r is None:
            r = bytes(c[pc + 2:pc + 2 + n]).decode("utf-8", "replace")
            self.strs[pc] = r
        return r, pc + 2 + n

    def run_program(self):
        return self.run(0, len(self.code), Scope(), True)

    def make_closure(self, start, end, scope, is_async, params):
        vm = self

        def fn(this, args):
            sc = Scope(scope)
            for i, (rest, name) in enumerate(params):
                if rest == 1:
                    sc.vars[name] = JSArray(args[i:])
                else:
                    sc.vars[name] = args[i] if i < len(args) else UNDEF
            if is_async:
                try:
                    return JSPromise(True, await_value(vm.run(start, end, sc, True)))
                except JSThrow as e:
                    return JSPromise(False, e.value)
            return vm.run(start, end, sc, False)
        return JSFunction(fn, "")

    def run(self, pc, end, scope, is_async):
        code = self.code
        disp = self.disp
        stack = []
        handlers = []
        push = stack.append
        pop = stack.pop
        tr = self.trace
        spec = self.spec
        lits = self.lits
        fast = self.fast
        while pc < end:
            try:
                while pc < end:
                    self.ops += 1
                    op = disp[code[pc]]
                    pc += 1
                    if op == OP_BINARY:
                        k = code[pc]
                        pc += 1
                        b = pop()
                        a = pop()
                        if type(a) is int and type(b) is int:
                            fc = fast[k]
                            if fc == 1:
                                r = a + b
                                if not -_MAXSAFE <= r <= _MAXSAFE:
                                    r = float(a) + float(b)
                            elif fc == 2:
                                r = a - b
                                if not -_MAXSAFE <= r <= _MAXSAFE:
                                    r = float(a) - float(b)
                            elif fc == 3:
                                r = a < b
                            elif fc == 4:
                                r = a > b
                            elif fc == 5:
                                r = a <= b
                            elif fc == 6:
                                r = a >= b
                            elif fc == 7:
                                r = a == b
                            elif fc == 8:
                                r = a != b
                            elif fc == 9 and -2147483648 <= a <= 2147483647 and -2147483648 <= b <= 2147483647:
                                r = a & b
                            elif fc == 10 and -2147483648 <= a <= 2147483647 and -2147483648 <= b <= 2147483647:
                                r = a | b
                            elif fc == 11 and -2147483648 <= a <= 2147483647 and -2147483648 <= b <= 2147483647:
                                r = a ^ b
                            elif fc == 12 and 0 <= a <= 0xFFFFFFFF and 0 <= b:
                                r = a >> (b & 31) if a <= 0x7FFFFFFF else ((a - 0x100000000) >> (b & 31))
                            elif fc == 13 and 0 <= b:
                                r = (a & 0xFFFFFFFF) >> (b & 31)
                            else:
                                r = binop(spec.binops[k], a, b)
                        else:
                            r = binop(spec.binops[k], a, b)
                        if tr is not None:
                            tr(["OP%d" % k, S(a), S(b), "=>", S(r)])
                        push(r)
                    elif op == OP_LOOKUP:
                        name, pc = self._str(pc)
                        s = scope.find(name)
                        if s is not None:
                            push(s.vars[name])
                        else:
                            v, _ = self._resolve(scope, name)
                            if v is _NF:
                                raise JSThrow(make_error(name, "Error"))
                            if tr is not None:
                                tr(["GV", name, S(v)])
                            push(v)
                    elif op == OP_LIT:
                        hit = lits.get(pc)
                        if hit is not None:
                            push(hit[0])
                            pc = hit[1]
                            continue
                        start = pc
                        t = spec.lit.get(code[pc])
                        pc += 1
                        cache = True
                        if t == LIT_STR:
                            v, pc = self._str(pc)
                        elif t == LIT_DOUBLE:
                            v = _rt.norm_num(_unpack_d(bytes(code[pc:pc + 8]))[0])
                            pc += 8
                        elif t == LIT_BOOL:
                            v = code[pc] != 0
                            pc += 1
                        elif t == LIT_NULL:
                            v = None
                        elif t == LIT_UNDEF:
                            v = UNDEF
                        elif t == LIT_BIGINT:
                            s, pc = self._str(pc)
                            v = JSBigInt(int(s, 0) if s[:2].lower() in ("0x", "0o", "0b") else int(s))
                        elif t == LIT_REGEX:
                            src, pc = self._str(pc)
                            fl, pc = self._str(pc)
                            v = JSRegExp(src, fl)
                            cache = False
                        else:
                            raise JSThrow(make_error("bad literal"))
                        if cache:
                            lits[start] = (v, pc)
                        push(v)
                    elif op == OP_INDEX_GET:
                        k = pop()
                        o = pop()
                        push(get_prop(o, k))
                    elif op == OP_GETPROP:
                        name, pc = self._str(pc)
                        o = pop()
                        push(get_prop(o, name))
                    elif op == OP_INDEX_SET:
                        v = pop()
                        k = pop()
                        o = pop()
                        set_prop(o, k, v)
                        push(v)
                    elif op == OP_SETPROP:
                        name, pc = self._str(pc)
                        v = pop()
                        o = pop()
                        set_prop(o, name, v)
                        push(v)
                    elif op == OP_METHOD_N:
                        n = code[pc]
                        pc += 1
                        name, pc = self._str(pc)
                        if n:
                            args = stack[-n:]
                            del stack[-n:]
                        else:
                            args = []
                        o = pop()
                        f = get_prop(o, name)
                        if not isinstance(f, JSFunction):
                            js_throw("%s.%s is not a function" % (type_of(o), name))
                        r = f.fn(o, args)
                        if tr is not None:
                            tr(["M", name, S(o), " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_METHOD_ARR:
                        name, pc = self._str(pc)
                        args = iterate(pop())
                        o = pop()
                        f = get_prop(o, name)
                        if not isinstance(f, JSFunction):
                            js_throw("%s.%s is not a function" % (type_of(o), name))
                        r = f.fn(o, args)
                        if tr is not None:
                            tr(["M2", name, S(o), " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_JZ:
                        t = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        if not truthy(pop()):
                            pc = t
                    elif op == OP_JNZ:
                        t = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        if truthy(pop()):
                            pc = t
                    elif op == OP_JMP:
                        pc = (code[pc] << 8) | code[pc + 1]
                    elif op == OP_DUP:
                        push(stack[-1])
                    elif op == OP_POP:
                        pop()
                    elif op == OP_SCOPE_ASSIGN:
                        name, pc = self._str(pc)
                        v = pop()
                        s = scope.find(name)
                        (s or scope).vars[name] = v
                    elif op == OP_CALL_GLOBAL:
                        n = code[pc]
                        pc += 1
                        name, pc = self._str(pc)
                        if n:
                            args = stack[-n:]
                            del stack[-n:]
                        else:
                            args = []
                        s = scope.find(name)
                        if s is not None:
                            f = s.vars[name]
                            local = True
                        else:
                            f, local = self._resolve(scope, name)
                            if f is _NF:
                                raise JSThrow(make_error(name, "Error"))
                        r = call_function(f, UNDEF, args)
                        if tr is not None:
                            tr(["G", name, " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_CALL_N:
                        n = code[pc]
                        pc += 1
                        if n:
                            args = stack[-n:]
                            del stack[-n:]
                        else:
                            args = []
                        f = pop()
                        r = call_function(f, UNDEF, args)
                        if tr is not None:
                            tr(["F2", S(f), " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_CALL_ARR:
                        args = iterate(pop())
                        f = pop()
                        r = call_function(f, UNDEF, args)
                        if tr is not None:
                            tr(["F", S(f), " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_UNARY:
                        k = code[pc]
                        pc += 1
                        a = pop()
                        r = unop(spec.unops[k], a)
                        if tr is not None:
                            tr(["U%d" % k, S(a), "=>", S(r)])
                        push(r)
                    elif op == OP_APPEND:
                        v = pop()
                        a = pop()
                        push(JSArray(iterate(a) + [v]))
                    elif op == OP_CONCAT:
                        b = pop()
                        a = pop()
                        push(JSArray(iterate(a) + iterate(b)))
                    elif op == OP_ARRAY_N:
                        n = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        if n:
                            arr = JSArray(stack[-n:])
                            del stack[-n:]
                        else:
                            arr = JSArray()
                        push(arr)
                    elif op == OP_OBJECT:
                        n = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        items = stack[-2 * n:] if n else []
                        if n:
                            del stack[-2 * n:]
                        o = JSObject()
                        for i in range(0, len(items), 2):
                            set_prop(o, items[i], items[i + 1])
                        push(o)
                    elif op == OP_SOFT_LOOKUP:
                        name, pc = self._str(pc)
                        v, _ = self._resolve(scope, name)
                        if v is _NF:
                            v = UNDEF
                            self.unresolved.add(name)
                        if tr is not None:
                            tr(["GV", name, S(v)])
                        push(v)
                    elif op == OP_CLOSURE:
                        c_async = code[pc] != 0
                        np_ = code[pc + 1]
                        pc += 2
                        params = []
                        for _ in range(np_):
                            rest = code[pc]
                            pc += 1
                            nm, pc = self._str(pc)
                            params.append((rest, nm))
                        ln = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        push(self.make_closure(pc, pc + ln, scope, c_async, params))
                        pc += ln
                    elif op == OP_NEW:
                        n = code[pc]
                        pc += 1
                        if n:
                            args = stack[-n:]
                            del stack[-n:]
                        else:
                            args = []
                        c = pop()
                        r = construct(c, args)
                        if tr is not None:
                            tr(["NEW", S(c), " ; ".join(S(x) for x in args), "=>", S(r)])
                        push(r)
                    elif op == OP_TRY_PUSH:
                        t = (code[pc] << 8) | code[pc + 1]
                        pc += 2
                        has = code[pc]
                        pc += 1
                        nm = None
                        if has:
                            nm, pc = self._str(pc)
                        handlers.append((t, nm))
                    elif op == OP_TRY_POP:
                        handlers.pop()
                    elif op == OP_AWAIT:
                        v = pop()
                        if not is_async:
                            raise JSThrow(make_error(""))
                        push(await_value(v))
                    elif op == OP_RET_POP:
                        return pop() if stack else UNDEF
                    elif op == OP_RET_TOP:
                        return stack[-1] if stack else UNDEF
                    elif op == OP_THROW:
                        raise JSThrow(pop())
                    elif op == OP_CONST:
                        name, pc = self._str(pc)
                        raise JSThrow(make_error(name))
                    else:
                        raise JSThrow(make_error("bad opcode %d at %d" % (code[pc - 1], pc - 1)))
                    if self.ops > self.max_ops:
                        raise RuntimeError("VM op budget exceeded")
            except JSThrow as e:
                if handlers:
                    t, nm = handlers.pop()
                    if nm:
                        scope.vars[nm] = e.value
                    pc = t
                else:
                    raise
            except (RuntimeError, RecursionError):
                raise
            except Exception as e:  # runtime bug / unsupported feature -> JS exception
                err = make_error("%s: %s" % (type(e).__name__, e), "InternalError")
                if tr is not None:
                    tr(["PYERR", repr(e)[:200]])
                if handlers:
                    t, nm = handlers.pop()
                    if nm:
                        scope.vars[nm] = err
                    pc = t
                else:
                    raise JSThrow(err)
        return stack[-1] if stack else UNDEF
