"""
Runner for the bytecode VMs hidden in VidCore / VidFast player pages
====================================================================
Their Next.js player chunk carries a small stack machine (generated by
an obfuscator) plus encrypted bytecode.  That bytecode builds the
encrypted API requests and decodes the replies, so to get a stream
without a browser we run the same bytecode here.

Every page build reshuffles the opcode numbers, XOR tables, global-name
tables and bytecode, so nothing is hard-coded: `find_vms(js)` reads all
of it straight from the chunk text each time:

  * the interpreter header  `function*t(r,l,h){var f=r,u=[],p=[];function m(){...return s[f++]^n[e%256]^o[e%256]^c}`
  * the XOR tables (murmur-style PRNG with a seed/step), the scalar XOR
    (`c=(r=r+1|0)-7|0`), the dispatch table (`d[l]=nD[l]^o[l]`)
  * the bytecode blocks and their concat order
  * each opcode's meaning, by recognising the shape of its `case` body
  * the global-name tables (`nk[[..].map(..fromCharCode(191^e))..]=fetch`)

The interpreter itself is synchronous (promises settle immediately).
"""

