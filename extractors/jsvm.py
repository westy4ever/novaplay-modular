def _match_brace(s, i):
    """s[i] is an opening bracket; return index of its partner.
    Skips string literals and (simple) regex literals."""
    pairs = {"{": "}", "(": ")", "[": "]"}
    stack = []
    n = len(s)
    j = i
    while j < n:
        c = s[j]
        if c in "\"'`":
            q = c
            j += 1
            while j < n and s[j] != q:
                if s[j] == "\\":
                    j += 1
                j += 1
        elif c in pairs:
            stack.append(pairs[c])
        elif c in ")}]":
            if not stack or stack[-1] != c:
                raise VMExtractError("unbalanced at %d" % j)
            stack.pop()
            if not stack:
                return j
        j += 1
    raise VMExtractError("no closing bracket")


def _split_cases(body):
    """body is the inside of a `switch(..){ ... }` -> [(label, text)]."""
    out = []
    depth = 0
    i = 0
    n = len(body)
    cur_label = None
    cur_start = None
    while i < n:
        c = body[i]
        if c in "\"'`":
            q = c
            i += 1
            while i < n and body[i] != q:
                if body[i] == "\\":
                    i += 1
                i += 1
            i += 1
            continue
        if c in "{([":
            depth += 1
        elif c in "})]":
            depth -= 1
        elif depth == 0:
            m = None
            if body.startswith("case ", i):
                m = re.match(r"case (\d+|\"[^\"]*\"):", body[i:])
            elif body.startswith("default:", i):
                m = re.match(r"default:", body[i:])
            if m and (i == 0 or body[i - 1] in ";{}:,)" or body[i - 1].isspace()):
                if cur_label is not None:
                    out.append((cur_label, body[cur_start:i]))
                lab = m.group(1) if m.lastindex else "default"
                cur_label = int(lab) if lab.isdigit() else lab
                cur_start = i + m.end()
                i += m.end()
                continue
        i += 1
    if cur_label is not None:
        out.append((cur_label, body[cur_start:]))
    return out


def _prng_table(seed, step, c1=0x85ebca6b, c2=0xc2b2ae35):
    t = bytearray(256)
    a = seed
    for r in range(256):
        a = (a + step) & 0xFFFFFFFF
        s = a
        s = ((s ^ (s >> 16)) * c1) & 0xFFFFFFFF
        s = ((s ^ (s >> 13)) * c2) & 0xFFFFFFFF
        s ^= s >> 16
        t[r] = s & 255
    return t


# ─── string-array deobfuscation (javascript-obfuscator style) ──────────

class StringDecoder(object):
    """Resolves `ck(652)`-style lookups of javascript-obfuscator's rotated
    string array (VidFast uses it on top of the VM)."""

    def __init__(self, js):
        self.js = js
        self.maps = {}

    def build(self):
        js = self.js
        arrays = {}
        for m in re.finditer(r"function (\w+)\(\)\{(?:let|var|const) (\w+)=\[", js):
            st = js.index("[", m.end() - 1)
            try:
                en = _match_brace(js, st)
                arr = _parse_js_string_array(js[st:en + 1])
            except Exception:
                continue
            if len(arr) >= 20:
                arrays[m.group(1)] = arr
        for arr_fn, arr in arrays.items():
            a = re.escape(arr_fn)
            decs = []
            # function DEC(e,t){let r=ARR();return(DEC=function(e,t){return r[e-=OFF]})(e,t)}
            for d in re.finditer(r"function (\w+)\(\w+,\w+\)\{(?:let|var|const) (\w+)=" + a +
                                 r"\(\);return\(\1=function\((\w+),\w+\)\{return \2\[\3-=(\d+|0x[0-9a-fA-F]+)\]", js):
                decs.append((d.group(1), int(d.group(4), 0)))
            # function DEC(e,t){return e-=OFF,ARR()[e]}
            for d in re.finditer(r"function (\w+)\((\w+),\w+\)\{return \2-=(\d+|0x[0-9a-fA-F]+),"
                                 + a + r"\(\)\[\2\]\}", js):
                decs.append((d.group(1), int(d.group(3), 0)))
            for dec, off in decs:
                rot = self._find_rotation(arr_fn, dec, off, arr)
                if rot is None:
                    continue
                self.maps[dec] = (arr[rot:] + arr[:rot], off)
        return self

    def _find_rotation(self, arr_fn, dec, off, arr):
        js = self.js
        rx = re.compile(r"function\((\w+),(\w+)\)\{(?:let|var|const) (\w+)=" + re.escape(dec) +
                        r",(\w+)=\1\(\);for\(;;\)try\{if\((.+?)===(\w+)\)break;")
        for m in rx.finditer(js):
            tail = js[m.end():m.end() + 300]
            tm = re.search(r"\}\)?\(" + re.escape(arr_fn) + r",(\d+|0x[0-9a-fA-F]+)\)", tail)
            if not tm:
                continue
            target = m.group(6)
            if target == m.group(2):
                target = tm.group(1)
            try:
                target = int(target, 0)
            except ValueError:
                continue
            rname = m.group(3)
            expr = m.group(5)
            n = len(arr)
            for rot in range(n):
                a2 = arr[rot:] + arr[:rot]
                try:
                    v = _eval_rot_expr(expr, rname, lambda i: a2[i - off])
                except Exception:
                    continue
                if abs(v - target) < 1e-6:
                    return rot
            return None
        return 0

    def resolve(self, text):
        """Replace DEC(123) and scoped aliases (`let r=DEC;` ... r(123))
        with the string literal."""
        if not self.maps:
            return text
        decs = self.maps
        dnames = "|".join(map(re.escape, decs))
        spans = {}   # alias -> [(start, end, dec)]
        for al in re.finditer(r"(?:let |var |const |,)(\w+)=(" + dnames + r")(?=[,;])", text):
            alias, dec = al.group(1), al.group(2)
            if alias in decs:
                continue
            st = al.start()
            j = _enclosing_brace(text, st)
            end = len(text)
            if j is not None:
                try:
                    end = _match_brace(text, j)
                except VMExtractError:
                    end = len(text)
            spans.setdefault(alias, []).append((st, end, dec))

        def rep(m):
            name = m.group(1)
            if m.start() > 0 and text[m.start() - 1] in ".$":
                return m.group(0)
            dec = None
            if name in decs:
                dec = name
            elif name in spans:
                best = None
                for st, en, d in spans[name]:
                    if st <= m.start() < en and (best is None or st > best[0]):
                        best = (st, d)
                if best:
                    dec = best[1]
            if dec is None:
                return m.group(0)
            arr, off = decs[dec]
            i = int(m.group(2), 0) - off
            if not 0 <= i < len(arr):
                return m.group(0)
            return '"' + arr[i].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
        names = set(decs) | set(spans)
        pat = r"(?<![\w$])(" + "|".join(map(re.escape, sorted(names, key=len, reverse=True))) + r")\((\d+|0x[0-9a-fA-F]+)\)"
        text = re.sub(pat, rep, text)
        # obj["prop"] -> obj.prop where it is a plain identifier
        text = re.sub(r'\[\"([A-Za-z_$][\w$]*)\"\]', r".\1", text)
        return text


def _enclosing_brace(text, pos, limit=200000):
    """index of the unmatched `{` that encloses pos (rough: ignores strings)."""
    depth = 0
    i = pos - 1
    stop = max(0, pos - limit)
    while i >= stop:
        c = text[i]
        if c == "}":
            depth += 1
        elif c == "{":
            if depth == 0:
                return i
            depth -= 1
        i -= 1
    return None


def _parse_js_string_array(src):
    out = []
    i = 1
    n = len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            q = c
            j = i + 1
            buf = []
            while src[j] != q:
                if src[j] == "\\":
                    nx = src[j + 1]
                    if nx == "x":
                        buf.append(chr(int(src[j + 2:j + 4], 16)))
                        j += 4
                        continue
                    if nx == "u":
                        buf.append(chr(int(src[j + 2:j + 6], 16)))
                        j += 6
                        continue
                    buf.append({"n": "\n", "t": "\t", "r": "\r", "0": "\0"}.get(nx, nx))
                    j += 2
                    continue
                buf.append(src[j])
                j += 1
            out.append("".join(buf))
            i = j + 1
        elif c in ",] \n":
            i += 1
        else:
            raise ValueError("non-string in array")
    return out


def _js_parse_int(s):
    m = re.match(r"\s*([+-]?\d+)", s)
    return int(m.group(1)) if m else float("nan")


def _eval_rot_expr(expr, rname, lookup):
    # e.g. -parseInt(r(437))/1+parseInt(r(744))/2*(-parseInt(r(300))/3)+...
    py = re.sub(r"parseInt\(" + re.escape(rname) + r"\((\d+|0x[0-9a-fA-F]+)\)\)",
                lambda m: "_pi(%d)" % int(m.group(1), 0), expr)
    if re.search(r"[A-Za-z_]\w*\(", py.replace("_pi(", "")):
        raise ValueError("unsupported expr")

    def _pi(i):
        v = _js_parse_int(lookup(i))
        if v != v:
            raise ValueError("nan")
        return v
    return eval(py, {"__builtins__": {}}, {"_pi": _pi})


