def _find_table_def(js, name, before):
    """var X=function(e){...a=0xSEED...a=a+0xSTEP>>>0;...}(0)"""
    pat = re.compile(r"(?:var |,|;|\s)" + re.escape(name) +
                     r"=function\(\w+\)\{(?:let \w+=\w+;)?for\(var \w+=new Uint8Array\(256\),\w+=(0x[0-9a-fA-F]+|\d+),\w+=0;"
                     r"\w+<256;\w+\+\+\)\{var \w+=\w+=\w+\+(0x[0-9a-fA-F]+|\d+)>>>0;(.{0,260}?)return \w+\}\(0\)")
    best = None
    for m in pat.finditer(js, 0, before):
        best = m
    if not best:
        raise VMExtractError("xor table %s not found" % name)
    tail = best.group(3)
    consts = re.findall(r"(0x[0-9a-fA-F]{6,8})", tail)
    c1 = int(consts[0], 16) if len(consts) > 0 else 0x85ebca6b
    c2 = int(consts[1], 16) if len(consts) > 1 else 0xc2b2ae35
    return _prng_table(int(best.group(1), 0), int(best.group(2), 0), c1, c2)


def _find_counter_scalar(js, name, before, region_start):
    """c=(r=r+1|0)-7|0  ->  value, counting r=r+1|0 since r=0."""
    m = None
    for mm in re.finditer(r"[,\s;]" + re.escape(name) + r"=\((\w+)=\1\+1\|0\)-(\d+)\|0", js[:before]):
        m = mm
    if not m:
        raise VMExtractError("scalar %s not found" % name)
    ctr = m.group(1)
    k = int(m.group(2))
    # counter init: last `ctr=0` before the region where it is incremented
    init = None
    for ii in re.finditer(r"(?:var |let |,|;)" + re.escape(ctr) + r"=0(?=[,;])(?!;\w+<)", js[:m.start()]):
        init = ii
    if not init:
        raise VMExtractError("counter init for %s not found" % ctr)
    seg = js[init.end():m.start() + 1]
    incs = len(re.findall(r"(?<![\w$])" + re.escape(ctr) + r"=" + re.escape(ctr) + r"\+1\|0", seg))
    val = incs + 1
    return (val - k) & 0xFFFFFFFF if (val - k) < 0 else (val - k)


def _parse_uint8_literal(js, name):
    m = re.search(r"[,;\s]" + re.escape(name) + r"=new Uint8Array\(\[([\d,\s]+)\]\)", js)
    if not m:
        raise VMExtractError("byte array %s not found" % name)
    return bytes(int(x) for x in m.group(1).split(","))


def _string_const(js, name):
    """np=[215,212,...].map(function(e){return String.fromCharCode(181^e)}).join("") or np="base64" """
    m = re.search(r"[,;\s]" + re.escape(name) +
                  r"=\[([\d,]+)\]\.map\(function\(e\)\{(?:let \w+=\w+;)?return String\.fromCharCode\((\d+)\^e\)\}\)\.join\(\"\"\)", js)
    if m:
        k = int(m.group(2))
        return "".join(chr(k ^ int(x)) for x in m.group(1).split(","))
    m = re.search(r"[,;\s]" + re.escape(name) + r"=\"([^\"]*)\"", js)
    if m:
        return m.group(1)
    raise VMExtractError("string const %s not found" % name)


def _resolve_encoding(js, expr, data):
    expr = expr.strip()
    if expr.startswith('"'):
        return expr.strip('"')
    if re.match(r"^\w+$", expr):
        try:
            return _string_const(js, expr)
        except VMExtractError:
            pass
    # unknown (e.g. obj._0x2faa18): guess from the data itself
    if re.match(r"^[0-9a-fA-F]*$", data) and len(data) % 2 == 0:
        return "hex"
    return "base64"


def _decode_block(js, name, bufname):
    """One bytecode block: new Uint8Array([...]) | BUF.from("..",ENC) |
    function(e,t){..BUF.from(e,ENC)..a[r]^=K..}("..",0)"""
    m = re.search(r"[,;\s]" + re.escape(name) + r"=new Uint8Array\(\[([\d,\s]+)\]\)", js)
    if m:
        return bytes(int(x) for x in m.group(1).split(","))
    m = re.search(r"[,;\s]" + re.escape(name) + r"=" + re.escape(bufname) +
                  r"\.from\(\"([^\"]*)\",([\w$.]+|\"\w+\")\)", js)
    if m:
        enc = _resolve_encoding(js, m.group(2), m.group(1))
        return _rt.buffer_from_string(m.group(1), enc)
    m = re.search(r"[,;\s]" + re.escape(name) + r"=function\(e,t\)\{(?:let \w+=\w+;)?for\(var (\w+)=" + re.escape(bufname) +
                  r"\.from\(e,([\w$.]+|\"\w+\")\),\w+=0;\w+<\1\.length;\w+\+\+\)\1\[\w+\]\^=(\d+);return \1\}\(\"([^\"]*)\",\d+\)",
                  js)
    if m:
        enc = _resolve_encoding(js, m.group(2), m.group(4))
        k = int(m.group(3))
        return bytes(b ^ k for b in _rt.buffer_from_string(m.group(4), enc))
    raise VMExtractError("bytecode block %s not found" % name)


def _concat_order(js, varname, before):
    """var s=function(){for(var e=Array(6),t=0;t<6;t++)switch(t){case 0:e[5]=ng;...}return nu.concat(e)}()"""
    m = None
    for mm in re.finditer(r"[,\s;]" + re.escape(varname) + r"=function\(\)\{for\(var e=(?:Array\(\d+\)|\[,*\]),t=0;t<(\d+);t\+\+\)switch\(t\)\{(.+?)\}return (\w+)\.concat\(e\)\}\(\)",
                          js[:before]):
        m = mm
    if not m:
        raise VMExtractError("bytecode concat for %s not found" % varname)
    n = int(m.group(1))
    slots = [None] * n
    for idx, nm in re.findall(r"e\[(\d+)\]=(\w+)", m.group(2)):
        slots[int(idx)] = nm
    return slots, m.group(3)


def _name_tables(js, tables):
    """All `T[[..].map(function(e){return String.fromCharCode(K^e)}).join("")]=VALUE` for T in tables."""
    out = {t: [] for t in tables}
    tpat = "|".join(map(re.escape, tables))
    rx = re.compile(r"(?<![\w$])(" + tpat + r")\[\[([\d,]+)\](?:\.map)?\(function\(e\)\{(?:let \w+=\w+;)?return String\.fromCharCode\((\d+)\^e\)\}\)\.join\(\"\"\)\]=")
    for m in rx.finditer(js):
        k = int(m.group(3))
        name = "".join(chr(k ^ int(x)) for x in m.group(2).split(","))
        # value expression up to the next top-level , or ;
        i = m.end()
        depth = 0
        j = i
        while j < len(js):
            c = js[j]
            if c in "([{":
                depth += 1
            elif c in ")]}":
                if depth == 0:
                    break
                depth -= 1
            elif c in ",;" and depth == 0:
                break
            j += 1
        out[m.group(1)].append((name, js[i:j]))
    # VidFast-style  T["Nsy87Fwwf~".split("").map(function(e){return String.fromCharCode(e.charCodeAt(0)-5)}).join("")]=V
    rx2 = re.compile(r"(?<![\w$])(" + tpat + r")\[\"((?:[^\"\\]|\\.)*)\"\.split\(\"\"\)\.map\(function\(e\)\{(?:let \w+=\w+;)?return String\.fromCharCode\(e\.charCodeAt\(0\)([-+])(\d+)\)\}\)\.join\(\"\"\)\]=([^,;]+)")
    for m in rx2.finditer(js):
        d = int(m.group(4)) * (-1 if m.group(3) == "-" else 1)
        raw = re.sub(r"\\(.)", r"\1", m.group(2))
        name = "".join(chr(ord(c) + d) for c in raw)
        out[m.group(1)].append((name, m.group(5)))
    return out


# --- case-body classification ---------------------------------------------------

def _classify(body, R):
    """R: dict of role -> identifier (byte, word, str, push, pop, stack, pc,
    handlers, scope, lookup, bin, un, const)."""
    b = body.strip().rstrip(";")
    # unify obfuscated property accesses  x["push"] / x.push
    b = re.sub(r'\[\"(\w+)\"\]', r".\1", b)
    B, W, S = R["byte"] + "()", R["word"] + "()", R["str"] + "()"
    POP = R["pop"] + "()"
    if "Object.create" in b:
        return OP_CLOSURE
    if "Reflect" in b and "construct" in b:
        return OP_NEW
    if "RegExp" in b:
        return OP_LIT
    if "hasOwnProperty" in b:
        return OP_SCOPE_ASSIGN
    if "void 0" in b and " in " in b:
        return OP_SOFT_LOOKUP
    if R.get("const") and (" in " + R["const"]) in b:
        return OP_CONST
    if "{c:" in b:
        return OP_TRY_PUSH
    m = re.match(r"^return (\d)$", b)
    if m:
        return {1: OP_RET_POP, 2: OP_RET_TOP, 3: OP_THROW, 4: OP_AWAIT}[int(m.group(1))]
    pc = R["pc"]
    if re.match(r"^return " + re.escape(pc) + r"=" + re.escape(W) + r",0$", b):
        return OP_JMP
    if POP + "||(" + pc + "=" in b:
        return OP_JZ
    if POP + "&&(" + pc + "=" in b:
        return OP_JNZ
    if re.match(r"^return " + re.escape(R["handlers"]) + r"\.pop\(\),0$", b):
        return OP_TRY_POP
    if b == "return " + POP + ",0":
        return OP_POP
    if R["stack"] + ".length-1]" in b and "splice" not in b:
        return OP_DUP
    if R.get("un") and R["un"] + "[" in b:
        return OP_UNARY
    if R.get("bin") and R["bin"] + "[" in b:
        return OP_BINARY
    spreads = b.count("[...")
    if spreads and ".call(" not in b and "(..." not in b:
        if b.count("...") >= 2:
            return OP_CONCAT
        return OP_APPEND
    if ".call(" in b:
        return OP_METHOD_N if "splice" in b else OP_METHOD_ARR
    if "splice" in b:
        if "2*" in b:
            return OP_OBJECT
        if "(..." in b:
            if R["lookup"] + "(" in b:
                return OP_CALL_GLOBAL
            return OP_CALL_N
        return OP_ARRAY_N
    if "(..." in b:
        return OP_CALL_ARR
    if re.search(re.escape(R["lookup"]) + r"\(" + re.escape(S) + r"\)", b) or \
            re.search(r"=" + re.escape(S) + r".*" + re.escape(R["lookup"]) + r"\(", b):
        return OP_LOOKUP
    has_s = S in b
    # property / index assignment:  o[k]=v  or  pop()[k]=v
    if re.search(r"\]=(?!=)", b):
        return OP_SETPROP if has_s else OP_INDEX_SET
    # property / index read:  push(o[k]) / push(pop()[k]) / push(pop()[str()])
    if "[" in b and R["push"] + "(" in b:
        return OP_GETPROP if has_s else OP_INDEX_GET
    raise VMExtractError("unrecognised opcode body: " + b[:160])


def _classify_literal(body, R):
    b = body.strip().rstrip(";")
    if "RegExp" in b:
        return LIT_REGEX
    if "readDouble" in b:
        return LIT_DOUBLE
    if "BigInt" in b:
        return LIT_BIGINT
    if "null" in b:
        return LIT_NULL
    if "0!==" in b:
        return LIT_BOOL
    if b == "return":
        return LIT_UNDEF
    if b == "return " + R["str"] + "()":
        return LIT_STR
    raise VMExtractError("unrecognised literal body: " + b[:120])


def deobfuscate(js):
    """Inline javascript-obfuscator string-array lookups, if the chunk has them."""
    if re.search(r"function (\w+)\(\)\{(?:let|var|const) \w+=\[\"", js) and "fromCharCode" in js:
        sd = StringDecoder(js).build()
        if sd.maps:
            return sd.resolve(js)
    return js


def find_vms(js, deobfuscated=False):
    """Parse every bytecode VM in a player chunk -> [VMSpec]."""
    if not deobfuscated:
        js = deobfuscate(js)
    specs = []
    hdr = re.compile(
        r"function\*(\w+)\((\w+),(\w+),(\w+)\)\{(?:let \w+=\w+;)?var (\w+)=\2,(\w+)=\[\],(\w+)=\[\];"
        r"function (\w+)\(\)\{if\(\5>=\3\)throw Error\(\"\"\);var e=\5;return ([^}]*)\}")
    for hm in hdr.finditer(js):
        try:
            specs.append(_parse_vm(js, hm))
        except VMExtractError:
            raise
    return specs


def _parse_vm(js, hm):
    spec = VMSpec()
    gen, p_start, p_end, p_scope, pc, stack, handlers, rbyte, expr = hm.groups()
    hstart = hm.start()
    # --- bytecode XOR decode expression
    terms = expr.split("^")
    code_var = None
    tables = []
    scalars = []
    for t in terms:
        m1 = re.match(r"^(\w+)\[" + re.escape(pc) + r"\+\+\]$", t)
        m2 = re.match(r"^(\w+)\[e%256\]$", t)
        if m1:
            code_var = m1.group(1)
        elif m2:
            tables.append(m2.group(1))
        elif re.match(r"^\w+$", t):
            scalars.append(t)
        else:
            raise VMExtractError("unknown decode term " + t)
    if not code_var:
        raise VMExtractError("no bytecode var")
    # the async wrapper before the generator: x=async function(){function e(e){return e in A?A[e]:...:SENT}
    pre = js[max(0, hstart - 600):hstart]
    nm = re.search(r"function (\w+)\((\w+)\)\{return ((?:\2 in \w+\?\w+\[\2\]:)+)(\w+)\}$", pre)
    if not nm:
        raise VMExtractError("name-table resolver not found")
    tnames = re.findall(r"\w+ in (\w+)\?", nm.group(3))
    sentinel = nm.group(4)
    # setup region: from the first name-table assignment for these tables
    first_assign = min((js.find(t + "[[") for t in tnames if js.find(t + "[[") >= 0), default=-1)
    region_start = first_assign if first_assign >= 0 else hstart - 20000
    # tables
    tvals = [_find_table_def(js, t, hstart) for t in tables]
    sc = 0
    for s in scalars:
        sc ^= _find_counter_scalar(js, s, hstart, region_start)
    # bytecode
    slots, bufname = _concat_order(js, code_var, hstart)
    raw = b"".join(_decode_block(js, nmx, bufname) for nmx in slots)
    code = bytearray(len(raw))
    for i, v in enumerate(raw):
        x = v ^ sc
        for t in tvals:
            x ^= t[i & 255]
        code[i] = x & 255
    spec.code = bytes(code)
    # --- helper function names inside the generator
    body_start = hm.end()
    gen_open = js.index("{", hm.start())
    gen_close = _match_brace(js, gen_open)
    G = js[body_start:gen_close]
    R = {"byte": rbyte, "pc": pc, "stack": stack, "handlers": handlers, "scope": p_scope}
    mw = re.search(r"function (\w+)\(\)\{return " + re.escape(rbyte) + r"\(\)<<8\|" + re.escape(rbyte) + r"\(\)\}", G)
    ms = re.search(r"function (\w+)\(\)\{for\(var \w+=(\w+)\(\),\w+=\w+\.alloc\(\w+\)", G)
    mpu = re.search(r"function (\w+)\(\w+\)\{" + re.escape(stack) + r"\.push\(\w+\)\}", G)
    mpo = re.search(r"function (\w+)\(\)\{if\(!" + re.escape(stack) + r"\.length\)throw Error\(\"\"\);return " +
                    re.escape(stack) + r"\.pop\(\)\}", G)
    mlk = re.search(r"function (\w+)\((\w+)\)\{if\(\2 in " + re.escape(p_scope) + r"\)return " + re.escape(p_scope) +
                    r"\[\2\];var \w+=\w+\(\2\);if\(\w+!==" + re.escape(sentinel) + r"\)return \w+;if\(\2 in (\w+)\)return \3\[\2\];throw Error\(\2\)\}", G)
    if not (mw and ms and mpu and mpo and mlk):
        raise VMExtractError("interpreter helpers not found (w=%s s=%s push=%s pop=%s lookup=%s)" % (
            bool(mw), bool(ms), bool(mpu), bool(mpo), bool(mlk)))
    R.update(word=mw.group(1), str=ms.group(1), push=mpu.group(1), pop=mpo.group(1), lookup=mlk.group(1))
    globals_obj = mlk.group(3)
    # op tables used inside
    mb = re.search(r"(\w+)\[\w+\]\(\w+,\w+\)", G)
    mu = re.search(r"(\w+)\[" + re.escape(rbyte) + r"\(\)\]\(" + re.escape(R["pop"]) + r"\(\)\)", G) or \
        re.search(r"(\w+)\[\w+\]\(" + re.escape(R["pop"]) + r"\(\)\)", G)
    mc = re.search(r"if\(!\(\w+ in (\w+)\)\)throw Error", G)
    R["bin"] = mb.group(1) if mb else None
    R["un"] = mu.group(1) if mu else None
    R["const"] = mc.group(1) if mc else None
    if R["bin"]:
        spec.binops = [_norm_bin(x) for x in _parse_op_table(js, R["bin"])]
    if R["un"]:
        spec.unops = [_norm_un(x) for x in _parse_op_table(js, R["un"])]
    # --- dispatch
    md = re.search(r"switch\((\w+)\[(\w+)\]\)\{case 0:", G)
    groups = []
    if md:
        dvar = md.group(1)
        sw_open = G.index("{", md.start())
        sw_close = _match_brace(G, sw_open)
        for lab, txt in _split_cases(G[sw_open + 1:sw_close]):
            if lab == "default":
                continue
            fm = re.search(r"function\((\w+)\)\{(?:let \w+=\w+;)?switch\(\1\)\{", txt)
            if not fm:
                raise VMExtractError("group %s has no switch" % lab)
            o = txt.index("{", fm.end() - 1)
            groups.append((lab, txt[o + 1:_match_brace(txt, o)]))
    else:
        ma = re.search(r"for\(var \w+=\[function", G)
        md2 = re.search(r"var \w+=\w+\(\),\w+=(\w+)\[(\w+)\[\w+\]\]\(\w+\)", G)
        if not (ma and md2):
            raise VMExtractError("dispatch not found")
        dvar = md2.group(2)
        arr_open = G.index("[", ma.start())
        arr_close = _match_brace(G, arr_open)
        arr = G[arr_open + 1:arr_close]
        idx = 0
        pos = 0
        while True:
            fm = re.compile(r"function\((\w+)\)\{(?:let \w+=\w+;)?switch\(\1\)\{").search(arr, pos)
            if not fm:
                break
            o = arr.index("{", fm.end() - 1)
            c = _match_brace(arr, o)
            groups.append((idx, arr[o + 1:c]))
            idx += 1
            pos = _match_brace(arr, arr.index("{", fm.start())) + 1
    mdisp = None
    for mm in re.finditer(r"(?:var |,|;)" + re.escape(dvar) + r"=new Uint8Array\(256\),(\w+)=0;\1<256;\1\+\+\)" +
                          re.escape(dvar) + r"\[\1\]=(\w+)\[\1\]\^(\w+)\[\1\]", js[:hstart]):
        mdisp = mm
    if not mdisp:
        raise VMExtractError("dispatch table %s not found" % dvar)
    base = _parse_uint8_literal(js, mdisp.group(2))
    tab = _find_table_def(js, mdisp.group(3), mdisp.start() + 1)
    group_of = [base[i] ^ tab[i] for i in range(256)]
    group_ops = {}
    for gi, gbody in groups:
        ops = {}
        for lab, txt in _split_cases(gbody):
            if lab == "default":
                continue
            op = _classify(txt, R)
            ops[lab] = op
            if op == OP_LIT:
                o = txt.index("switch(")
                o = txt.index("{", o)
                for l2, t2 in _split_cases(txt[o + 1:_match_brace(txt, o)]):
                    if l2 != "default":
                        spec.lit[l2] = _classify_literal(t2, R)
        group_ops[gi] = ops
    for byte in range(256):
        g = group_of[byte]
        ops = group_ops.get(g)
        if ops and byte in ops:
            spec.disp[byte] = ops[byte]
    # --- name tables
    nt = _name_tables(js, tnames)
    spec.table_names = [nt[t] for t in tnames]
    spec.uses_globals = bool(globals_obj)
    spec.label = "%s@%d" % (gen, hstart)
    return spec


