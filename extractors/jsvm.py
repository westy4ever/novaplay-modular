def _parse_op_table(js, name, depth=0):
    """nE=[(e,t)=>e+t,...].concat([...]) or nE=A.concat(B) with A/B defined
    elsewhere (also as obj._0xabc=[...]) -> list of the arrow bodies."""
    if depth > 6:
        raise VMExtractError("operator table recursion")
    m = None
    for mm in re.finditer(r"(?<![\w$])" + re.escape(name) + r"=(?!=)", js):
        nxt = js[mm.end():mm.end() + 1]
        if nxt in "[" or re.match(r"[\w$]", nxt):
            m = mm
            if nxt == "[":
                break
    if not m:
        raise VMExtractError("operator table %s not found" % name)
    i = m.end()
    ops = []
    while True:
        if js[i] == "[":
            j = _match_brace(js, i)
            part = js[i + 1:j]
            for item in re.findall(r"\(?(?:\w+,\w+|\w+|)\)?=>\s*([^,\]]+)", part):
                ops.append(item.strip())
            i = j + 1
        else:
            rm = re.match(r"[\w$]+(?:\.[\w$]+)*", js[i:])
            if not rm:
                raise VMExtractError("bad operator table expr for " + name)
            ref = rm.group(0)
            if ref.endswith(".concat"):
                ref = ref[:-7]
            ops.extend(_parse_op_table(js, ref, depth + 1))
            i += len(ref)
        rest = js[i:i + 10]
        if rest.startswith(".concat("):
            i += 8
            continue
        if rest.startswith(").concat("):
            i += 9
            continue
        break
    return ops


def _norm_bin(expr):
    e = expr.replace(" ", " ")
    # names of the two params may differ: normalise to e/t
    m = re.match(r"^(\w+)\s*(===|!==|==|!=|>>>|>>|<<|<=|>=|\*\*|[-+*/%|&^<>]| in | instanceof )\s*(\w+)$", e)
    if not m:
        raise VMExtractError("unknown binary op " + expr)
    return m.group(2).strip()


def _norm_un(expr):
    e = expr.strip()
    if e.startswith("void"):
        return "void"
    if e.startswith("typeof"):
        return "typeof"
    m = re.match(r"^([-~+!])\w+$", e)
    if not m:
        raise VMExtractError("unknown unary op " + expr)
    return m.group(1)


